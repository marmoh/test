import { Arena, World, newHero, Bot, BOTS, seedOf, talentsForLevel, type MinionType } from '../../sim/src/index.js';
import { loadRooms } from './content-io.js';
const rooms = loadRooms();
const room = rooms.find((r) => r.id === 'room_01')!;
const hero = newHero(talentsForLevel(1));
const ws = [Array.from({ length: 3 }, (_, i) => ({ type: 'jelly' as MinionType, c: 1 + ((i * 3) % 7), r: 1 + ((i * 2) % 8) }))];
const w = new World({ arena: new Arena(room), D: 1, waves: ws, seed: seedOf(0, 3) }, hero);
const bot = new Bot(BOTS.expert, seedOf(0, 5)) as any;
bot.beginRoom();
const T = Number(process.argv[2] ?? 2.0);
while (w.t < T) w.step(bot.input(w));
console.log('ch', bot.ch.map((x: number) => x.toFixed(0)).join(','));
console.log('loopPath', Array.from(bot.loopPath as Float64Array).map((x) => x.toFixed(0)).join(','));
console.log('plan', bot.plan && { cx: bot.plan.cx, cy: bot.plan.cy, r: bot.plan.r, dir: bot.plan.dir, circ: bot.plan.circling });
console.log('th', bot.th.length, 'zs', bot.zs.length);
